    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
String Name = jTextField1.getText();

    if (Name.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter Food NAME.");
        return;
    }

    try {
        Connection con = DBconnection.getConnection();

        String sql = "DELETE FROM food WHERE Name = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, Name);

        int result = pst.executeUpdate();

        if (result > 0) {
            JOptionPane.showMessageDialog(this, "Food deleted successfully!");
            jTextField1.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Food Name not found.");
        }

        pst.close();
        con.close();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Food Name must be a Word.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

