    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
String id = jTextField1.getText();
    String name = jTextField2.getText();
    String price = jTextField3.getText();
    String category = jTextField4.getText();

    if (id.isEmpty() || name.isEmpty() || price.isEmpty() || category.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields.");
        return;
    }

    try {
        Connection con = DBconnection.getConnection();

        String sql = "UPDATE food SET Name = ?, Price = ?, Category = ? WHERE Id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, name);
        pst.setDouble(2, Double.parseDouble(price));
        pst.setString(3, category);
        pst.setInt(4, Integer.parseInt(id));

        int result = pst.executeUpdate();

        if (result > 0) {
            JOptionPane.showMessageDialog(this, "Food updated successfully!");
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Food ID not found.");
        }

        pst.close();
        con.close();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID and Price must be numbers.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

