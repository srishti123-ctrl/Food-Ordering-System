    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
    String foodName = jTextField1.getText().trim();
    String quantityText = jTextField2.getText().trim();

    if (foodName.isEmpty() || quantityText.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter food name and quantity."
        );

        return;
    }

    try {

        int quantity = Integer.parseInt(quantityText);

        if (quantity <= 0) {

            JOptionPane.showMessageDialog(
                this,
                "Quantity must be greater than 0."
            );

            return;
        }

        Connection con = DBconnection.getConnection();

        String sql = "SELECT Price FROM Food WHERE Name = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, foodName);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            double price = rs.getDouble("Price");

            double total = price * quantity;

            model.addRow(
                new Object[]{
                    foodName,
                    quantity,
                    price,
                    total
                }
            );

            calculateGrandTotal();

            jTextField1.setText("");
            jTextField2.setText("");

            jTextField1.requestFocus();

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Food not found in menu."
            );
        }

        rs.close();
        pst.close();
        con.close();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid quantity."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton5ActionPerformed

