    private void loadBill(int orderId) {

    String sql =
        "SELECT o.order_id, o.order_date, o.grand_total, " +
        "oi.food_name, oi.quantity, oi.price, oi.total " +
        "FROM orders o " +
        "JOIN order_items oi ON o.order_id = oi.order_id " +
        "WHERE o.order_id = ?";

    try {

        Connection con = DBconnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, orderId);

        ResultSet rs = pst.executeQuery();

        model.setRowCount(0);

        boolean found = false;

        while (rs.next()) {

            found = true;

            // Order information
            jTextField1.setText(
                String.valueOf(rs.getInt("order_id"))
            );

            jTextField6.setText(
                rs.getString("order_date")
            );

            // Add food item to table
            model.addRow(new Object[]{
                rs.getString("food_name"),
                rs.getInt("quantity"),
                rs.getDouble("price"),
                rs.getDouble("total")
            });
        }

        if (found) {

            // Grand total
            // Change jTextField5 to the text field
            // you are using for Grand Total
            jTextField2.setText(
                getGrandTotal(orderId)
            );

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Order not found."
            );
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
    private String getGrandTotal(int orderId) {

    String sql =
        "SELECT grand_total FROM orders WHERE order_id = ?";

    try {

        Connection con = DBconnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, orderId);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            double grandTotal = rs.getDouble("grand_total");

            rs.close();
            pst.close();
            con.close();

            return String.format("%.2f", grandTotal);
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

    return "0.00";
}
    

