    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                       

    String foodName = jTextField1.getText().trim();
    String priceText = jTextField2.getText().trim();
    String category = jTextField3.getText().trim();

    // Check empty fields
    if (foodName.isEmpty() || priceText.isEmpty() || category.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please fill all fields.");
        return;
    }

    try {
        // Convert price to number
        double price = Double.parseDouble(priceText);

        // Connect to database
        Connection con = DBconnection.getConnection();

        // Insert food
        String sql = "INSERT INTO food (Name, Price, Category) VALUES (?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, foodName);
        pst.setDouble(2, price);
        pst.setString(3, category);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Food added successfully!");

        // Clear fields
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");

        pst.close();
        con.close();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid price.\nExample: 250");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
    }


   
    }//GEN-LAST:event_jButton2ActionPerformed

